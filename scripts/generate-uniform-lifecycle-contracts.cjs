const fs = require('node:fs');
const path = require('node:path');

// Generate the same workload and access policy at each uniform integer width.
function source(platform, width) {
  const plain = platform === 'Plain';
  const zama = platform === 'Zama';
  const type = `${plain ? '' : 'e'}uint${width}`;
  const external = plain ? type : `externalEuint${width}`;
  const permission = plain ? '' : `FHE.allowThis(value); ${zama ? 'FHE.allow(value, msg.sender);' : 'FHE.allowSender(value);'}`;
  const imports = plain ? '' : zama
    ? `import {FHE, ${type}, ${external}, eaddress, externalEaddress} from "@fhevm/solidity/lib/FHE.sol";\nimport {ZamaEthereumConfig} from "@fhevm/solidity/config/ZamaConfig.sol";\n`
    : `import {FHE, ${type}, ${external}, eaddress, externalEaddress} from "@fhenixprotocol/cofhe-contracts-current/FHE.sol";\n`;
  const ownerType = plain ? 'address' : 'eaddress';
  const ownerInput = plain ? 'address' : 'externalEaddress';
  const add = plain ? 'total[SMART_METER_ID] + last[SMART_METER_ID]' : 'FHE.add(total[SMART_METER_ID], last[SMART_METER_ID])';
  const mean = plain ? '(last[SMART_METER_ID] + total[SMART_METER_ID]) / 2'
    : zama ? 'FHE.div(FHE.add(last[SMART_METER_ID], total[SMART_METER_ID]), 2)'
      : `FHE.div(FHE.add(last[SMART_METER_ID], total[SMART_METER_ID]), FHE.asEuint${width}(uint256(2)))`;
  const product = plain ? 'last[SMART_METER_ID] * scalar'
    : zama ? 'FHE.mul(last[SMART_METER_ID], scalar)'
      : `FHE.mul(last[SMART_METER_ID], FHE.asEuint${width}(uint256(scalar)))`;
  const maximum = plain ? 'last[SMART_METER_ID] > total[SMART_METER_ID] ? last[SMART_METER_ID] : total[SMART_METER_ID]'
    : 'FHE.max(last[SMART_METER_ID], total[SMART_METER_ID])';
  return `// SPDX-License-Identifier: GPL-3.0
// Generated by scripts/generate-uniform-lifecycle-contracts.cjs.
pragma solidity ^0.8.27;
${imports}
contract EnergyUniform${platform}${width}${zama ? ' is ZamaEthereumConfig' : ''} {
    address public immutable owner = msg.sender;
    bytes32 public constant SMART_METER_ID = bytes32("energy-benchmark-smart-meter-001");
    mapping(bytes32 => ${ownerType}) private meterOwners;
    mapping(bytes32 => ${type}) private last;
    mapping(bytes32 => ${type}) private total;
    mapping(bytes32 => ${type}) private result;
    bool private meterRegistered;
    bool private initialized;
    event OperationCompleted(address indexed user, uint8 operation);
    event MeterOwnerRegistered(bytes32 indexed meterId);

    modifier allowed() { require(msg.sender == owner, "Not authorized"); _; }
    modifier hasEntry() { require(initialized, "No entry"); _; }

    // Associate this meter with an owner address supplied by the benchmark operator.
    // FHE variants import a confidential address; this association does not change caller authorization.
    function setSmartMeterOwner(bytes32 meterId, ${ownerInput} input${plain ? '' : ', bytes calldata proof'}) external allowed {
        require(meterId == SMART_METER_ID, "Unknown smart meter");
        ${ownerType} value = ${plain ? 'input' : zama ? 'FHE.fromExternal(input, proof)' : 'FHE.asEaddress(input, proof)'};
        ${plain ? '' : permission}
        meterOwners[meterId] = value;
        meterRegistered = true;
        emit MeterOwnerRegistered(meterId);
    }

    // Read the owner associated with the requested public smart-meter identifier.
    // FHE variants return an eaddress handle for authorized client-side decryption.
    function getSmartMeterOwner(bytes32 meterId) external view allowed returns (${ownerType}) {
        require(meterId == SMART_METER_ID && meterRegistered, "Unknown smart meter");
        return meterOwners[meterId];
    }

    // Register the latest reading at the campaign's selected width.
    // The encrypted variants authenticate the input and grant persistent access.
    function addEnergyEntry(${external} input${plain ? '' : ', bytes calldata proof'}) external allowed {
        require(meterRegistered, "Meter owner not registered");
        ${type} value = ${plain ? 'input' : zama ? 'FHE.fromExternal(input, proof)' : `FHE.asEuint${width}(input, proof)`};
        grant(value);
        last[SMART_METER_ID] = value;
        initialized = true;
        emit OperationCompleted(msg.sender, 0);
    }

    // Add the latest reading to the accumulator at the same width.
    // Store the updated total and grant access to its encrypted handle.
    function addLastEntryToEncryptedTotal() external allowed hasEntry returns (${type}) {
        ${plain ? 'unchecked {' : ''}
        ${type} value = ${add};
        grant(value);
        total[SMART_METER_ID] = value;
        emit OperationCompleted(msg.sender, 1);
        return value;
        ${plain ? '}' : ''}
    }

    // Multiply the latest reading by a public scalar of the campaign width.
    // CoFHE represents the scalar as a trivial encryption at that same width.
    function multiplyLastEntryByConstant(uint${width} scalar) external allowed hasEntry returns (${type}) {
        ${plain ? 'unchecked {' : ''}
        return storeResult(${product}, 2);
        ${plain ? '}' : ''}
    }

    // Compute the integer mean after the width-specific addition.
    // Store the result and grant access to its encrypted handle.
    function meanLastEntryAndEncryptedTotal() external allowed hasEntry returns (${type}) {
        ${plain ? 'unchecked {' : ''}
        return storeResult(${mean}, 3);
        ${plain ? '}' : ''}
    }

    // Compute the maximum of the latest reading and accumulated total.
    // Store the result using the same access policy as the other operations.
    function maxLastEntryAndEncryptedTotal() external allowed hasEntry returns (${type}) {
        return storeResult(${maximum}, 4);
    }

    // Read the persisted reading from this campaign's state.
    // Encrypted variants return a handle for client-side plaintext retrieval.
    function getLastEntryValue() external view allowed hasEntry returns (${type}) { return last[SMART_METER_ID]; }
    // Read the persisted total from this campaign's state.
    // Encrypted variants return a handle for client-side plaintext retrieval.
    function getEncryptedTotalHandle() external view allowed returns (${type}) { return total[SMART_METER_ID]; }
    // Read the last persisted arithmetic output without issuing an FHE operation.
    // This getter is used by the separate view-plus-decrypt measurement.
    function getLastResult() external view allowed returns (${type}) { return result[SMART_METER_ID]; }

    function storeResult(${type} value, uint8 operation) private returns (${type}) {
        grant(value);
        result[SMART_METER_ID] = value;
        emit OperationCompleted(msg.sender, operation);
        return value;
    }
    function grant(${type}${plain ? ' /* value */' : ' value'}) private${plain ? ' pure' : ''} { ${permission} }
}
`;
}

const folder = path.resolve(__dirname, '../contracts/uniform');
const check = process.argv.includes('--check');
if (!check) fs.mkdirSync(folder, { recursive: true });
for (const width of [16, 128]) {
  for (const platform of ['Plain', 'Zama', 'CoFHE']) {
    const file = path.join(folder, `EnergyUniform${platform}${width}.sol`);
    const expected = source(platform, width);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== expected) {
        throw new Error(`Generated contract differs: ${path.basename(file)}`);
      }
    } else fs.writeFileSync(file, expected);
  }
}
